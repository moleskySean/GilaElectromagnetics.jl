# Generates the wavefronts drawn in driving_fields.tex and
# scattering_decomposition.tex, plus the shared scatterer outline.
#
# 2D scalar toy problem in figure units (the panels are 4.5 x 3.6):
#   plane wave along +x, a small line source, and a scatterer with contrast chi,
#   solved with a dense Lippmann-Schwinger system on a pulse grid.
# Wavefronts are the zero contours of Re(u), one every half wavelength.
#
# Run from this directory:  julia scattering_fields.jl
using Pkg
Pkg.activate(temp=true); Pkg.add(["Contour", "SpecialFunctions"]; io=devnull)
using Contour, SpecialFunctions, LinearAlgebra

const λ = 0.9
const k = 2π / λ
const χ = 1.5               # scatterer contrast (eps = 1 + chi)
const W, H = 4.5, 3.6       # panel size
const src = (0.75, 0.7)     # line source position
const amp = 2.5             # line source strength
const centre = (2.75, 1.7)  # scatterer centre

# Scatterer outline: periodic Catmull-Rom spline through these control points
# (relative to the centre). Everything else in the notes reads the outline
# from data/scatterer_path.tex, so edit the shape here only.
const ctrl = [(-1.15, -0.65), (-0.2, -0.95), (0.95, -0.75), (1.3, 0.05), (0.9, 0.8),
              (0.0, 0.7), (-0.45, 0.95), (-1.2, 0.55), (-1.4, -0.05)]

function outline(pts; per=14)
    n = length(pts)
    out = Tuple{Float64,Float64}[]
    for i in 1:n
        p0, p1, p2, p3 = pts[mod1(i - 1, n)], pts[i], pts[mod1(i + 1, n)], pts[mod1(i + 2, n)]
        for t in range(0, 1; length=per + 1)[1:end-1]
            c(a, b, c_, d) = 0.5 * (2b + (-a + c_) * t + (2a - 5b + 4c_ - d) * t^2 + (-a + 3b - 3c_ + d) * t^3)
            push!(out, (c(p0[1], p1[1], p2[1], p3[1]), c(p0[2], p1[2], p2[2], p3[2])))
        end
    end
    out
end

function inside(poly, x, y)
    c = false
    n = length(poly)
    for i in 1:n
        (x1, y1), (x2, y2) = poly[i], poly[mod1(i + 1, n)]
        if (y1 > y) != (y2 > y) && x < x1 + (y - y1) * (x2 - x1) / (y2 - y1)
            c = !c
        end
    end
    c
end

G(r) = 0.25im * hankelh1(0, k * r)  # 2D scalar Green function

# ---- solve for the polarization inside the scatterer ----
shape = [(x + centre[1], y + centre[2]) for (x, y) in outline(ctrl)]
h = 0.04
cells = [(x, y) for x in 0:h:W for y in 0:h:H if inside(shape, x, y)]
N = length(cells)
a = h / sqrt(π)                                      # equal-area disk radius
self = 1im * π * a / (2k) * hankelh1(1, k * a) - 1 / k^2
u_inc(x, y) = cis(k * x)
u_imp(x, y) = amp * hankelh1(0, k * hypot(x - src[1], y - src[2]))
u_drv(x, y) = u_inc(x, y) + u_imp(x, y)

A = Matrix{ComplexF64}(I, N, N)
Threads.@threads for j in 1:N
    for i in 1:N
        A[i, j] -= k^2 * χ * (i == j ? self : G(hypot(cells[i][1] - cells[j][1], cells[i][2] - cells[j][2])) * h^2)
    end
end
u_cells = A \ [u_drv(c...) for c in cells]
println("scatterer cells: $N")

# ---- evaluate every field on the panel grid ----
xs, ys = 0:0.025:W, 0:0.025:H
inc = [u_inc(x, y) for x in xs, y in ys]
imp = [u_imp(x, y) for x in xs, y in ys]
sca = zeros(ComplexF64, length(xs), length(ys))
Threads.@threads for ix in eachindex(xs)
    for iy in eachindex(ys)
        x, y = xs[ix], ys[iy]
        sca[ix, iy] = k^2 * χ * h^2 * sum(u_cells[j] * G(max(hypot(x - cells[j][1], y - cells[j][2]), a))
                                           for j in 1:N)
    end
end
fields = Dict("inc" => inc, "imp" => imp, "drv" => inc .+ imp, "sca" => sca, "tot" => inc .+ imp .+ sca)

# ---- write TikZ data ----
mkpath("data")
for (name, u) in fields
    open("data/field_$name.tex", "w") do io
        println(io, "% generated by scattering_fields.jl: zero contours of Re(u_$name)")
        for line in lines(contour(xs, ys, real.(u), 0.0))
            xv, yv = coordinates(line)
            length(xv) < 4 && continue
            pts = join(("($(round(x; digits=3)),$(round(y; digits=3)))" for (x, y) in zip(xv[1:2:end], yv[1:2:end])), " ")
            println(io, "\\fieldline{$pts}")
        end
    end
end
open("data/scatterer_path.tex", "w") do io
    println(io, "% generated by scattering_fields.jl: the shared scatterer outline, centred on the origin")
    pts = join(("($(round(x; digits=3)),$(round(y; digits=3)))" for (x, y) in outline(ctrl)), " ")
    println(io, "\\newcommand\\scattererpath{plot[smooth cycle] coordinates {$pts}}")
end
